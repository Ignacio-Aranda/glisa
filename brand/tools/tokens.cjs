function css() {
  const sharedLines = Object.entries(shared).map(([k, v]) => `  ${k}: ${v};`).join('\n');
  const lightLines = Object.entries(light).map(([k, v]) => `  ${k}: ${v};`).join('\n');
  const darkLines = (ind) => Object.entries(dark).map(([k, v]) => `${ind}${k}: ${v};`).join('\n');
  return `/* Design tokens. GENERATED by brand/tools/tokens.cjs: edit that file, then run
   \`node brand/tools/tokens.cjs\`. Names are fixed by docs/ARCHITECTURE.md; guide: docs/BRAND.md.

   Themes: light is the default (:root). Put data-theme="dark" | "light" | "system" on <html>;
   "system" follows prefers-color-scheme. */

:root {
${sharedLines}

${lightLines}
  color-scheme: light;
}

[data-theme="dark"] {
${darkLines('  ')}
  color-scheme: dark;
}

@media (prefers-color-scheme: dark) {
  [data-theme="system"] {
${darkLines('    ')}
    color-scheme: dark;
  }
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --dur-fast: 1ms;
    --dur-med: 1ms;
    --dur-slow: 1ms;
    --ease-spring: cubic-bezier(0.22, 1, 0.36, 1);
  }
}
`;
}

/** Concrete values for a theme ("light" | "dark"), used to rasterize without a browser. */
function resolve(theme) {
  return { ...shared, ...light, ...(theme === 'dark' ? dark : {}) };
}

module.exports = { shared, light, dark, resolve, css };

