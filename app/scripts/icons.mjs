#!/usr/bin/env node
// Generates src/lib/components/icons.ts: the lucide icons the window uses, as plain SVG
// node data taken from @lucide/svelte (so the bundle carries data, not one compiled
// component per icon). Add a name to NAMES and run `npm run icons`.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP = dirname(dirname(fileURLToPath(import.meta.url)));
const ICONS = join(APP, 'node_modules', '@lucide', 'svelte', 'dist', 'icons');

export const NAMES = `
app-window arrow-down arrow-down-up arrow-left arrow-left-right arrow-left-to-line arrow-right
arrow-right-to-line arrow-up ban battery battery-charging battery-exclamation-point battery-full
battery-low battery-medium bell bluetooth cable camera check chevron-down chevron-left
chevron-right chevron-up chevrons-left chevrons-right circle circle-arrow-left
circle-arrow-right circle-check circle-dot circle-exclamation-point circle-question-mark
clipboard-list clipboard-paste computer copy disc-3 ellipsis external-link face-slightly-smiling
fingerprint-pattern folder folder-open gauge globe accessibility house image image-off info
key-round keyboard languages laptop layers layout-grid link loader-circle lock maximize-2
mic-off minimize-2 minus monitor monitor-cog monitor-smartphone moon mouse mouse-left
mouse-pointer-2 mouse-pointer-click mouse-right move network palette panel-left panel-right
pen-line pencil play plus pointer power radio-receiver redo-2 refresh-ccw refresh-cw rocket
rotate-ccw scan scissors search settings settings-2 shield shield-check skip-back skip-forward
square-dashed-text square-mouse-pointer sun sun-dim sun-moon terminal trash
triangle-exclamation-point undo-2 usb volume-1 volume-2 volume-x wand-sparkles waypoints wifi x
zoom-in zoom-out
`.trim().split(/\s+/);

const out = [
  '// GENERATED by scripts/icons.mjs from @lucide/svelte (ISC license): do not edit by hand.',
  '// Each icon is a list of [element, attributes] drawn on a 24×24 grid.',
  '',
  'export type IconNode = [string, Record<string, string>][];',
  '',
  'export const ICONS: Record<string, IconNode> = {',
];
const missing = [];
for (const name of [...new Set(NAMES)].sort()) {
  let src;
  try {
    src = readFileSync(join(ICONS, name + '.svelte'), 'utf8');
  } catch {
    missing.push(name);
    continue;
  }
  const m = /__iconData = (\{.*?\});\n/s.exec(src);
  if (!m) { missing.push(name); continue; }
  const data = JSON.parse(m[1]);
  out.push(`  '${name}': ${JSON.stringify(data.node)},`);
}
out.push('};', '');
if (missing.length) {
  console.error('unknown icons (use the canonical lucide name):', missing.join(', '));
  process.exit(1);
}
writeFileSync(join(APP, 'src', 'lib', 'components', 'icons.ts'), out.join('\n'));
console.log(`${NAMES.length} icons`);
